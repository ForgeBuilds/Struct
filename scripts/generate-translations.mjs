import fs from "node:fs/promises";

const LOCALE_DIR = new URL("../src/locales/", import.meta.url);
const CACHE = new URL("../src/translation-cache.json", import.meta.url);
const OUTPUT = new URL("../src/generatedTranslations.ts", import.meta.url);
const LOCALES = ["hi", "zh", "es", "fr", "de", "ja", "ko", "pt", "ru"];
const LANGUAGE_NAMES = {
  hi: "Hindi", zh: "Simplified Chinese", es: "Spanish", fr: "French", de: "German",
  ja: "Japanese", ko: "Korean", pt: "Portuguese", ru: "Russian",
};
const BATCH_SIZE = 35;

function parseResponse(text) {
  const stripped = text.trim().replace(/^```(?:json)?\s*/i, "").replace(/\s*```$/, "");
  return JSON.parse(stripped);
}

function placeholders(text) {
  return [...text.matchAll(/\{\w+\}/g)].map(([item]) => item).sort().join("|");
}

async function translateBatch(locale, entries, apiKey, endpoint, model) {
  const response = await fetch(endpoint, {
    method: "POST",
    headers: { Authorization: `Bearer ${apiKey}`, "Content-Type": "application/json" },
    body: JSON.stringify({
      model,
      temperature: 0.1,
      response_format: { type: "json_object" },
      messages: [
        { role: "system", content: `Translate UI strings from English to ${LANGUAGE_NAMES[locale]}. Return only a JSON object with exactly the same keys and translated string values. Preserve every {placeholder} exactly, preserve markup and product names, keep concise UI wording, and do not translate URLs, code, provider names, or proper nouns.` },
        { role: "user", content: JSON.stringify(entries) },
      ],
    }),
  });
  if (!response.ok) throw new Error(`Translation request failed (${response.status}): ${(await response.text()).slice(0, 500)}`);
  const data = await response.json();
  const content = data.choices?.[0]?.message?.content;
  if (typeof content !== "string") throw new Error("Translation provider returned no text content.");
  const translated = parseResponse(content);
  for (const [key, source] of Object.entries(entries)) {
    if (typeof translated[key] !== "string") throw new Error(`Missing translation for ${locale}:${key}`);
    if (placeholders(source) !== placeholders(translated[key])) throw new Error(`Placeholder mismatch in ${locale}:${key}`);
  }
  return translated;
}

const apiKey = process.env.TRANSLATION_API_KEY || process.env.OPENAI_API_KEY;
const dryRun = process.argv.includes("--dry-run");
if (!apiKey && !dryRun) {
  console.error("Set TRANSLATION_API_KEY (or OPENAI_API_KEY) before generating locale translations.");
  console.error("The generated translations are bundled with the app; generation is the only step that calls the provider.");
  process.exit(1);
}

const endpoint = process.env.TRANSLATION_API_URL || "https://api.openai.com/v1/chat/completions";
const model = process.env.TRANSLATION_MODEL || "gpt-4o-mini";
const english = JSON.parse(await fs.readFile(new URL("en.json", LOCALE_DIR), "utf8"));
if (!english || !Object.keys(english).length) throw new Error("Could not read src/locales/en.json.");
const localeOverrides = {};
for (const locale of LOCALES) {
  localeOverrides[locale] = JSON.parse(await fs.readFile(new URL(`${locale}.json`, LOCALE_DIR), "utf8"));
}
const cache = JSON.parse(await fs.readFile(CACHE, "utf8").catch(() => "{}"));

if (dryRun) {
  for (const locale of LOCALES) {
    const current = localeOverrides[locale] ?? {};
    const todo = Object.entries(english).filter(([key, value]) => !current[key] && cache[locale]?.[key]?.source !== value);
    console.log(`${locale}: ${todo.length} strings need generated translations`);
  }
  process.exit(0);
}

for (const locale of LOCALES) {
  const current = localeOverrides[locale] ?? {};
  cache[locale] ??= {};
  const todo = Object.entries(english).filter(([key, value]) => !current[key] && cache[locale][key]?.source !== value);
  console.log(`${locale}: generating ${todo.length} missing strings`);
  for (let i = 0; i < todo.length; i += BATCH_SIZE) {
    const batch = Object.fromEntries(todo.slice(i, i + BATCH_SIZE));
    const translated = await translateBatch(locale, batch, apiKey, endpoint, model);
    for (const [key, source] of Object.entries(batch)) cache[locale][key] = { source, translation: translated[key] };
  }
}

const generated = {};
for (const locale of LOCALES) {
  const current = localeOverrides[locale] ?? {};
  const translated = {};
  for (const [key, value] of Object.entries(english)) {
    const cached = cache[locale]?.[key];
    if (!current[key] && cached?.source === value && typeof cached.translation === "string") translated[key] = cached.translation;
  }
  generated[locale] = translated;
}
await fs.writeFile(CACHE, `${JSON.stringify(cache, null, 2)}\n`);
const output = `/** Generated by npm run translations:generate. Do not edit by hand. */\nimport type { LocaleCode } from "./i18n";\n\nexport const GENERATED_TRANSLATIONS: Partial<Record<LocaleCode, Record<string, string>>> = ${JSON.stringify(generated, null, 2)};\n`;
await fs.writeFile(OUTPUT, output);
console.log("Generated locale fallback bundle.");
